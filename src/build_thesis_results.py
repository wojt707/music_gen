def get_first_pass_validity_rates() -> dict[str, float]:
    """
    Parse first-pass generation validity rates:
      1. For LSTM, Transformer, LLaMA: parsed from clean_defective_midis_log.txt
         (first-generation audit of 16,000 files prior to deleting defective tracks).
      2. For Moonbeam: parsed from generation_log.csv inside generated_midis_archives/*.tar.gz
         (Moonbeam was generated entirely with automated audit and retry logging enabled).
    """
    rates = {}

    # 1. Models evaluated in clean_defective_midis_log.txt
    if DEFECTIVE_MIDIS_LOG_PATH.exists():
        try:
            text = DEFECTIVE_MIDIS_LOG_PATH.read_text(encoding="utf-8")
            pattern = re.compile(r'\[([^\]]+)\]\s+Total:\s+(\d+)\s+\|\s+Valid:\s+(\d+)\s+\|\s+Defective:\s+(\d+)')
            matches = pattern.findall(text)
            counts = defaultdict(lambda: {"total": 0, "valid": 0})
            for path_str, tot, val, _ in matches:
                parts = path_str.split("/")
                if len(parts) == 3:
                    m = parts[2]
                    counts[m]["total"] += int(tot)
                    counts[m]["valid"] += int(val)
            for m, s in counts.items():
                if s["total"] > 0:
                    rates[m] = round((s["valid"] / s["total"]) * 100, 1)
        except Exception as e:
            print(f"Warning parsing {DEFECTIVE_MIDIS_LOG_PATH}: {e}")

    # 2. Moonbeam generation audit logs from archives
    archives_dir = SYNC_DIR / "generated_midis_archives"
    if archives_dir.exists():
        mb_total = 0
        mb_valid = 0
        for tar_file in archives_dir.glob("*moonbeam*.tar.gz"):
            try:
                with tarfile.open(tar_file, "r:gz") as tar:
                    members = [m.name for m in tar.getmembers() if "generation_log.csv" in m.name]
                    for m_name in members:
                        f = tar.extractfile(m_name)
                        reader = csv.DictReader(io.TextIOWrapper(f, encoding="utf-8"))
                        for r in reader:
                            if r.get("model") == "moonbeam":
                                mb_total += 1
                                if r.get("first_attempt_valid") == "1":
                                    mb_valid += 1
            except Exception:
                pass
        if mb_total > 0:
            rates["moonbeam"] = round((mb_valid / mb_total) * 100, 1)

    return rates


