def get_classifier_statistics() -> list[dict]:
    """Parse test accuracy and F1 for all 8 trained RoBERTa classifiers."""
    job_map = {
        3389885: ("gt_1000_with_ties", "piano", 12),
        3389886: ("gt_1000_with_ties", "multi-instrument", 12),
        3389888: ("gt_1000_no_ties", "piano", 10),
        3389889: ("gt_1000_no_ties", "multi-instrument", 10),
        3389890: ("top_5_with_ties", "piano", 5),
        3389891: ("top_5_with_ties", "multi-instrument", 5),
        3389892: ("top_5_no_ties", "piano", 5),
        3389893: ("top_5_no_ties", "multi-instrument", 5),
    }

    results = []
    for job_id, (ds, sp, num_g) in job_map.items():
        err_file = SLURM_DIR / f"musicgen_classifier_{job_id}" / "error.err"
        test_acc = None
        test_f1 = None
        test_loss = None
        if err_file.exists():
            with open(err_file, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    if "Test Results:" in line:
                        try:
                            d_str = line.split("Test Results:")[1].strip()
                            d = ast.literal_eval(d_str)
                            test_acc = d.get("test_accuracy")
                            test_f1 = d.get("test_f1")
                            test_loss = d.get("test_loss")
                        except Exception:
                            pass

        random_chance = 1.0 / num_g
        factor_over_random = (test_acc / random_chance) if test_acc else 0.0

        results.append({
            "job_id": job_id,
            "taxonomy": ds,
            "split": sp,
            "num_genres": num_g,
            "test_accuracy": round(test_acc * 100, 1) if test_acc else None,
            "test_f1": round(test_f1, 3) if test_f1 else None,
            "test_loss": round(test_loss, 3) if test_loss else None,
            "random_baseline": round(random_chance * 100, 1),
            "factor_over_random": round(factor_over_random, 2),
        })
    return results


