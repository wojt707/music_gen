def generate_table_08_repetition_novelty(master_rows: list[dict]):
    """T8: Structural Self-Repetition and Training Corpus Memorization Rates vs Real Human Baseline."""
    out_file = THESIS_TABLES_DIR / "tab08_repetition_novelty.tex"

    def get_avg_metric(metric_base: str, m: str, sp: str) -> tuple[str, str]:
        mean_key = f"{metric_base}_mean"
        std_key = f"{metric_base}_std"
        m_rows = [r for r in master_rows if r.get("model") == m and r.get("split") == sp and r.get(mean_key)]
        if not m_rows:
            return "---", "---"
        means = [float(r[mean_key]) for r in m_rows]
        stds = [float(r[std_key]) if r.get(std_key) else 0.0 for r in m_rows]
        k = len(means)
        avg_val = sum(means) / k
        # Mathematically rigorous pooled standard deviation across disjoint test partitions:
        # s_pooled = sqrt((1/k) * sum(s_i^2 + (mu_i - mu_bar)^2))
        pooled_var = sum(s**2 + (mu - avg_val)**2 for mu, s in zip(means, stds)) / k
        pooled_std = math.sqrt(max(0.0, pooled_var))
        return f"{avg_val:.3f}", f"{pooled_std:.3f}"

    models = ["real", "lstm", "transformer", "llama", "moonbeam"]

    def build_panel_rows(sp: str) -> list[str]:
        p_rows = []
        for m in models:
            m_name = "Real Human Baseline" if m == "real" else CANONICAL_MODELS[m]
            r_rep, s_rep = get_avg_metric("self_repetition_4gram", m, sp)
            r_lcs, s_lcs = get_avg_metric("max_lcs_ratio", m, sp)
            r_6g, s_6g = get_avg_metric("train_6gram_overlap", m, sp)

            rep_str = f"{r_rep} $\\pm$ {s_rep}" if r_rep != "---" else "---"
            lcs_str = f"{r_lcs} $\\pm$ {s_lcs}" if r_lcs != "---" else "---"
            ov6_str = f"{r_6g} $\\pm$ {s_6g}" if r_6g != "---" else "---"

            prefix = r"\textbf{" if m == "real" else ""
            suffix = r"}" if m == "real" else ""
            p_rows.append(rf"{prefix}{m_name}{suffix} & {rep_str} & {lcs_str} & {ov6_str} \\")
        return p_rows

    piano_rows = "\n".join(build_panel_rows("piano"))
    multi_rows = "\n".join(build_panel_rows("multi-instrument"))

    header = (
        r"\textbf{Model} & "
        r"\makecell{\textbf{Self-Repetition}\\\textbf{(4-Gram)}} & "
        r"\makecell{\textbf{Max LCS}\\\textbf{Ratio}} & "
        r"\makecell{\textbf{6-Gram Overlap}\\\textbf{with Training}} \\"
    )

    content = rf"""\begin{{table}}[htbp]
\centering
\small
\caption{{Intra-song self-repetition and training corpus memorization metrics across models.}}
\label{{tab:repetition_novelty}}
\begin{{tabular*}}{{\linewidth}}{{@{{\extracolsep{{\fill}}}}lccc@{{}}}}
\toprule
{header}
\midrule
\multicolumn{{4}}{{l}}{{\textbf{{Domain: Solo Piano}}}} \\
{piano_rows}
\addlinespace
\multicolumn{{4}}{{l}}{{\textbf{{Domain: Multi-instrument}}}} \\
{multi_rows}
\bottomrule
\end{{tabular*}}
\vskip 1ex
\footnotesize\raggedright
Values report grand mean and pooled standard deviation ($s_{{\text{{pooled}}}} = \sqrt{{\frac{{1}}{{K}}\sum (s_i^2 + (\mu_i - \bar{{\mu}})^2)}}$) across all 4 experimental datasets. Self-repetition represents the proportion of repeated 4-token pitch n-grams within the same piece. Max LCS Ratio quantifies the longest contiguous pitch subsequence matching any training track normalized on 256-note prefixes. 6-Gram Overlap denotes the proportion of generated 6-note sequences present verbatim in the training corpus.
\end{{table}}
"""
    out_file.write_text(content, encoding="utf-8")


