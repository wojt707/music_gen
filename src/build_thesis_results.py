def get_dataset_statistics() -> list[dict]:
    """Collect track counts, unique artists, and genre counts across all 8 configurations."""
    rows = []
    configs = [
        ("gt_1000_with_ties", "piano", 12),
        ("gt_1000_with_ties", "multi-instrument", 12),
        ("gt_1000_no_ties", "piano", 10),
        ("gt_1000_no_ties", "multi-instrument", 10),
        ("top_5_with_ties", "piano", 5),
        ("top_5_with_ties", "multi-instrument", 5),
        ("top_5_no_ties", "piano", 5),
        ("top_5_no_ties", "multi-instrument", 5),
    ]

    for ds, sp, expected_genres in configs:
        split_dir = SPLITS_DIR / ds / "split" / sp
        train_csv = split_dir / "train.csv"
        val_csv = split_dir / "val.csv"
        test_csv = split_dir / "test.csv"
        gw_json = split_dir / "genre_weights.json"

        def count_file(path: Path) -> tuple[int, int]:
            if not path.exists():
                return 0, 0
            tracks = 0
            artists = set()
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                reader = csv.DictReader(f)
                for r in reader:
                    tracks += 1
                    a = r.get("artist_name") or r.get("artist") or r.get("artist_id")
                    if a:
                        artists.add(a.strip())
            return tracks, len(artists)

        train_tracks, train_artists = count_file(train_csv)
        val_tracks, val_artists = count_file(val_csv)
        test_tracks, test_artists = count_file(test_csv)
        total_tracks = train_tracks + val_tracks + test_tracks
        total_artists = train_artists + val_artists + test_artists

        # Genre counts & imbalance
        num_genres = expected_genres
        max_ratio = 1.0
        if gw_json.exists():
            with open(gw_json, "r", encoding="utf-8") as f:
                gw = json.load(f)
                num_genres = len(gw)
                # inverse frequency weights: max_w / min_w gives imbalance ratio
                weights = list(gw.values())
                if weights and min(weights) > 0:
                    max_ratio = max(weights) / min(weights)

        rows.append({
            "taxonomy": ds,
            "split": sp,
            "num_genres": num_genres,
            "train_tracks": train_tracks,
            "val_tracks": val_tracks,
            "test_tracks": test_tracks,
            "total_tracks": total_tracks,
            "total_artists": total_artists,
            "imbalance_ratio": round(max_ratio, 2),
        })
    return rows


